"""Switch off recipes / loot tables that can never load in this pack, and document them.

Usage:  python -I tools/disable_broken.py            (reads server/logs/latest.log of the last full boot)

A recipe or loot table that logs "Unknown registry key" points at an item, potion, serializer ...
that doesn't exist in this pack (an unfinished item, or a compat recipe for a mod we don't run).
It never worked, so overriding it with NeoForge's `neoforge:false` condition loses nothing and
stops the ERROR on every start.

Writes:   server/kubejs/data/<ns>/recipe|loot_table/<path>.json   (the overrides)
          docs/broken-data.md                                       (what was disabled and why)
Re-run after adding mods: entries whose missing IDs now exist are reported so you can delete them.
"""
import json
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
ROOT = Path(__file__).resolve().parent.parent
LOG = ROOT / "server" / "logs" / "latest.log"
DATA = ROOT / "server" / "kubejs" / "data"
DOC = ROOT / "docs" / "broken-data.md"
OFF = {"neoforge:conditions": [{"type": "neoforge:false"}]}
KEYS = re.compile(r"minecraft:(\w+)\]: ([\w:./-]+)")


def main():
    lines = LOG.read_text(encoding="utf-8", errors="replace").splitlines()
    found = {}  # (kind, id) -> set of missing keys
    for l in lines:
        if "/ERROR]" not in l:
            continue
        m = re.search(r"Parsing error loading recipe ([\w:/.-]+): (.*)", l)
        kind = "recipe"
        if not m:
            m = re.search(r"Couldn't parse element ResourceKey\[minecraft:root / minecraft:loot_table\]:([\w:/.-]+) - (.*)", l)
            kind = "loot_table"
        if not m:
            continue
        rid, msg = m.groups()
        missing = {f"{reg}:{key}" for reg, key in KEYS.findall(msg)}
        if missing and ("Unknown registry key" in msg or "recipe_serializer" in msg):
            found[(kind, rid)] = missing

    written = 0
    for (kind, rid), missing in found.items():
        ns, path = rid.split(":", 1)
        out = DATA / ns / kind / f"{path}.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        if not out.exists():
            out.write_text(json.dumps(OFF) + "\n", encoding="utf-8", newline="\n")
            written += 1

    # Merge with what the doc already lists, so re-runs keep history.
    rows = {}
    if DOC.exists():
        for l in DOC.read_text(encoding="utf-8").splitlines():
            m = re.match(r"\| `(recipe|loot_table)` \| `([^`]+)` \| (.*) \|$", l)
            if m:
                rows[(m[1], m[2])] = m[3]
    for (kind, rid), missing in found.items():
        rows[(kind, rid)] = ", ".join(f"`{x}`" for x in sorted(missing))
    doc = ["# Disabled broken data", "",
           "Generated by `tools/disable_broken.py`. Each recipe or loot table below logged *Unknown registry key*:",
           "it points at something that doesn't exist in this pack, so it could never work. Each one is overridden in",
           "`server/kubejs/data/<ns>/<kind>/<path>.json` with `{\"neoforge:conditions\":[{\"type\":\"neoforge:false\"}]}`.",
           "If a later mod adds the missing ID, delete that override.", "",
           "| Kind | ID | Missing in this pack |", "|---|---|---|"]
    doc += [f"| `{k}` | `{i}` | {why} |" for (k, i), why in sorted(rows.items())]
    DOC.write_text("\n".join(doc) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(found)} broken recipe/loot entries in this log; {written} new overrides written; {len(rows)} documented in {DOC.name}")


if __name__ == "__main__":
    main()
