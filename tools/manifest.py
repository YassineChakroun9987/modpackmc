"""Write mods-manifest.txt (every jar in the pack, with its side and SHA-1) and check client sync.

Usage:  python -I tools/manifest.py

Jars aren't committed to git, so git tracks this file instead:
- `git diff mods-manifest.txt` shows exactly which mods were added, removed or updated.
- The SHA-1 lets us re-download the identical file from Modrinth (API: /version_file/<sha1>).

Side is worked out by comparing folders:
  in server/mods and the client instance  -> both
  in server/mods only                      -> server
  in client-only/                          -> client
It also warns about jars that are in the client instance but nowhere in the pack (strays),
and client-only jars that are missing from the client instance.
"""
import hashlib
import os
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # Windows console defaults to cp1252

ROOT = Path(__file__).resolve().parent.parent
SERVER = ROOT / "server" / "mods"
CLIENT_ONLY = ROOT / "client-only"
INSTANCE = Path(os.environ["APPDATA"]) / ".minecraft" / "versions" / "greenlanterns" / "mods"
OUT = ROOT / "mods-manifest.txt"


def jars(folder):
    return {p.name: p for p in folder.glob("*.jar")} if folder.exists() else {}


def sha1(path):
    return hashlib.sha1(path.read_bytes()).hexdigest()


def main():
    server, client_only, instance = jars(SERVER), jars(CLIENT_ONLY), jars(INSTANCE)
    rows = []
    for name, p in server.items():
        rows.append(("both" if name in instance else "server", name, sha1(p)))
    for name, p in client_only.items():
        rows.append(("client", name, sha1(p)))
    rows.sort(key=lambda r: (["both", "server", "client"].index(r[0]), r[1].lower()))

    width = max(len(r[1]) for r in rows)
    lines = [
        "# Every mod jar in the pack. Generated by tools/manifest.py - don't edit by hand.",
        "# side    file" + " " * (width - 4) + "  sha1",
    ] + [f"{side:<8}{name:<{width}}  {digest}" for side, name, digest in rows]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")  # LF, like the repo

    counts = {s: sum(1 for r in rows if r[0] == s) for s in ("both", "server", "client")}
    print(f"Wrote {OUT.name}: {len(rows)} jars ({counts['both']} both, {counts['server']} server, "
          f"{counts['client']} client)")

    problems = 0
    for name in sorted(set(instance) - set(server) - set(client_only)):
        print(f"   STRAY     {name} is in the greenlanterns instance but not in the pack")
        problems += 1
    for name in sorted(set(client_only) - set(instance)):
        print(f"   MISSING   {name} (client-only) is not in the greenlanterns instance")
        problems += 1
    for name in sorted(set(client_only) & set(instance)):
        if sha1(client_only[name]) != sha1(instance[name]):
            print(f"   DIFFERENT {name}: client-only/ and the instance have different files")
            problems += 1
    for name in sorted(set(server) & set(instance)):
        if sha1(server[name]) != sha1(instance[name]):
            print(f"   DIFFERENT {name}: server/mods and the instance have different files")
            problems += 1
    print("Client instance is in sync." if not problems else f"{problems} sync problem(s).")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
